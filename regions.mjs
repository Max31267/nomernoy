// Generate the drop pool and labels from one catalog so they cannot drift apart.
const entries = catalog.flatMap(([name, codes]) => codes.split(' ').map(code => [code, name]));
export const REGIONS = Object.freeze(entries.map(([code]) => code));
export const REGION_NAMES = Object.freeze(Object.fromEntries(entries));

export function regionName(code) {
  return REGION_NAMES[String(code).padStart(2, '0')] || 'Регион';
}
