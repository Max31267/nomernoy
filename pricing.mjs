export function specialSeries(plate) {
  const code=plate.letters.join(''),region=String(plate.region).padStart(2,'0');
  const exact=SERIES_RULES.find(rule=>rule.code===code&&rule.regions.includes(region));
  if(exact)return {...exact,matched:true,label:`Спецсерия ${code} · ${region}`};
  if(collectible[code])return {code,regions:[],minimum:collectible[code],matched:false,label:`Коллекционные буквы ${code}`};
  return null;
}

function digitPremium(digits,region) {
  let factor=1;
  if(/^([0-9])\1\1$/.test(digits))factor=digits==='777'?3.4:digits==='999'?3:2.6;
  else if(/^00[1-9]$/.test(digits))factor=digits==='007'?3.2:2.8;
  else if(digits.endsWith('00'))factor=1.65;
  else if(['123','234','345','456','567','678','789','987','876','765','654','543','432','321'].includes(digits))factor=1.6;
  else if(digits[0]===digits[2])factor=1.35;
  if(digits===String(region).padStart(3,'0'))factor*=1.25;
  return factor;
}

export function appraisePlate(plate) {
  const series=specialSeries(plate);
  if(!series)return {...plate,pricingVersion:PRICING_VERSION};
  const fingerprint=[...(plate.letters.join('')+plate.digits+plate.region)].reduce((n,c)=>(n*31+c.charCodeAt(0))>>>0,0);
  const minimum=Math.round(series.minimum*digitPremium(plate.digits,plate.region)*(1+(fingerprint%21)/100)/100)*100;
  const tags=plate.tags.filter(tag=>typeof tag==='string'&&tag!=='Классическое сочетание'&&!tag.startsWith('Спецсерия ')&&!tag.startsWith('Коллекционные буквы '));
  return {...plate,value:Math.max(plate.value,minimum),tags:[series.label,...tags],pricingVersion:PRICING_VERSION};
}
